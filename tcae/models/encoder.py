def _no_grad_trunc_normal_(tensor, mean, std, a, b):
    # Cut & paste from PyTorch official master until it's in a few official releases - RW
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1. + math.erf(x / math.sqrt(2.))) / 2.


    with torch.no_grad():
        # Values are generated by using a truncated uniform distribution and
        # then using the inverse CDF for the normal distribution.
        # Get upper and lower cdf values
        l = norm_cdf((a - mean) / std)
        u = norm_cdf((b - mean) / std)

        # Uniformly fill tensor with values from [l, u], then translate to
        # [2l-1, 2u-1].
        tensor.uniform_(2 * l - 1, 2 * u - 1)

        # Use inverse cdf transform for normal distribution to get truncated
        # standard normal
        tensor.erfinv_()

        # Transform to proper mean, std
        tensor.mul_(std * math.sqrt(2.))
        tensor.add_(mean)

        # Clamp to ensure it's in the proper range
        tensor.clamp_(min=a, max=b)
        return tensor


def trunc_normal_(tensor, mean=0., std=1., a=-2., b=2.):
    # type: (Tensor, float, float, float, float) -> Tensor
    return _no_grad_trunc_normal_(tensor, mean, std, a, b)




class ViTBaseEncoder(nn.Module):
    def __init__(self, config, compress_type='conv', use_ssl=False, ssl_cfg=None) -> None:
        super().__init__()
        self.config = config
        self.patch_size = config.patch_size
        
        self.patch_embed = PatchEmbed2D(
            patch_size=config.patch_size,
            num_channels=config.num_channels,
            hidden_size=config.hidden_size,
        )
        self.num_tokens_stage1 = (config.image_size // config.patch_size) ** 2 
        self.num_tokens_stage2 = (config.image_size // (config.patch_size * 2)) ** 2
        
        num_layers_per_stage = 6
        self.layers_stage1 = nn.ModuleList([VisionLayer(config) for _ in range(num_layers_per_stage)])
        self.layers_stage2 = nn.ModuleList([VisionLayer(config) for _ in range(config.num_hidden_layers - num_layers_per_stage)])
        
        self.compress_mode = compress_type  # [conv  or pixel_shuffle]
        
        self.spatial_compress = nn.Sequential(
            nn.LayerNorm(config.hidden_size, eps=config.layer_norm_eps),)
        
        if self.compress_mode == 'conv':
            self.compress_conv = nn.Sequential(
                nn.Conv2d(config.hidden_size, config.hidden_size, kernel_size=3, stride=2, padding=1),
                nn.GELU(),
                nn.Conv2d(config.hidden_size, config.hidden_size, kernel_size=3, stride=1, padding=1),
            )
        elif self.compress_mode == 'pixel_shuffle':
            self.compress_mlp = nn.Sequential(
                nn.Linear(config.hidden_size * 4, config.hidden_size * 2),
                nn.GELU(),
                nn.Linear(config.hidden_size * 2, config.hidden_size),
            )
        else:
            raise ValueError(f"Unknown compress_mode: {compress_mode}")
        
        self.layernorm = nn.LayerNorm(config.hidden_size, eps=config.layer_norm_eps)
        
        self.use_ssl = use_ssl

        if not use_ssl:
            self.position_embeddings_stage1 = nn.Parameter(torch.randn(1, self.num_tokens_stage1, config.hidden_size))
            self.position_embeddings_stage2 = nn.Parameter(torch.randn(1, self.num_tokens_stage2, config.hidden_size))
            self.num_cls_tokens = 0
            self.num_register_tokens = 0
        else:
            self.num_cls_tokens = ssl_cfg.num_cls_tokens
            # Stage 1 position embeddings
            self.position_embeddings_stage1 = nn.Parameter(torch.randn(1, self.num_cls_tokens + self.num_tokens_stage1, config.hidden_size))
            self.position_embeddings_stage2 = nn.Parameter(torch.randn(1, self.num_cls_tokens + self.num_tokens_stage2, config.hidden_size))
            self.interpolate_offset = ssl_cfg.interpolate_offset
            self.interpolate_antialias = ssl_cfg.interpolate_antialias
            self.num_register_tokens = ssl_cfg.num_register_tokens
            self.cls_token = (nn.Parameter(torch.zeros(1, self.num_cls_tokens, config.hidden_size))  if self.num_cls_tokens > 0 else None)
            self.register_tokens = (nn.Parameter(torch.zeros(1, self.num_register_tokens, config.hidden_size))  if self.num_register_tokens > 0 else None)
            self.mask_token = nn.Parameter(torch.zeros(1, config.hidden_size))

        torch.nn.init.normal_(self.position_embeddings_stage1, std=self.config.initializer_range)
        torch.nn.init.normal_(self.position_embeddings_stage2, std=self.config.initializer_range)

        self.gradient_checkpointing = False
        self.apply(self._init_weights)


    def _init_weights(self, m):
        if isinstance(m, (nn.Linear, nn.Conv2d)):
            trunc_normal_(m.weight, std=.02)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)
        elif isinstance(m, nn.Embedding):
            trunc_normal_(m.weight, std=.02)
            if m.padding_idx is not None:
                m.weight.data[m.padding_idx].zero_()


    def spatial_downsample_conv(self, hidden_states):
        B, N, C = hidden_states.shape
        H = W = int(N ** 0.5)  # H/8, W/8
        hidden_states = hidden_states.reshape(B, H, W, C).permute(0, 3, 1, 2)
        hidden_states = self.compress_conv(hidden_states)
        hidden_states = hidden_states.permute(0, 2, 3, 1).reshape(B, -1, C)
        return hidden_states


    def spatial_downsample_pixelshuffle(self, hidden_states):
        B, N, C = hidden_states.shape
        H = W = int(N ** 0.5)  # H/8, W/8
        hidden_states = hidden_states.reshape(B, H, W, C)
        hidden_states = hidden_states.reshape(B, H // 2, 2, W // 2, 2, C)
        hidden_states = hidden_states.permute(0, 1, 3, 2, 4, 5).reshape(B, H // 2, W // 2, 4 * C)
        hidden_states = hidden_states.reshape(B, -1, 4 * C)
        hidden_states = self.compress_mlp(hidden_states)
        return hidden_states


    def spatial_downsample(self, hidden_states):
        """
        Downsample patch tokens from (H/8, W/8) to (H/16, W/16) using two optional methods
        Input: [B, N1, C] where N1 = (H/8) * (W/8)
        Output: [B, N2, C] where N2 = (H/16) * (W/16)
        """
        if self.compress_mode == 'conv':
            return self.spatial_downsample_conv(hidden_states)
        elif self.compress_mode == 'pixel_shuffle':
            return self.spatial_downsample_pixelshuffle(hidden_states)
        else:
            raise ValueError(f"Unknown compress_mode: {self.compress_mode}")


    def forward(
        self,
        hidden_states,
    ):
        # ========== Stage 1: Patch Size 8 ==========
        hidden_states = self.patch_embed(hidden_states)
        
        if self.num_cls_tokens == 0:
            hidden_states = hidden_states + self.position_embeddings_stage1
        else:
            hidden_states = torch.cat((self.cls_token.expand(hidden_states.shape[0], -1, -1), hidden_states), dim=1)
            hidden_states = hidden_states + self.position_embeddings_stage1

        for layer in self.layers_stage1:
            if self.gradient_checkpointing and self.training:
                hidden_states = self._gradient_checkpointing_func(
                    layer.__call__, hidden_states, None
                )
            else:
                hidden_states = layer(hidden_states, None)

        # ========== Spatial Downsampling ==========
        if self.num_cls_tokens > 0:
            cls_tokens = hidden_states[:, :self.num_cls_tokens]
            image_tokens = hidden_states[:, self.num_cls_tokens:]
            image_tokens = self.spatial_compress(image_tokens)
            image_tokens = self.spatial_downsample(image_tokens)
            hidden_states = torch.cat([cls_tokens, image_tokens], dim=1)
            # add stage 2 position embeddings
            hidden_states = hidden_states + self.position_embeddings_stage2
        else:
            hidden_states = self.spatial_compress(hidden_states)
            hidden_states = self.spatial_downsample(hidden_states)
            hidden_states = hidden_states + self.position_embeddings_stage2

        # ========== Stage 2: Patch Size 16 ==========
        for layer in self.layers_stage2:
            if self.gradient_checkpointing and self.training:
                hidden_states = self._gradient_checkpointing_func(
                    layer.__call__, hidden_states, None
                )
            else:
                hidden_states = layer(hidden_states, None)

        hidden_states_norm = self.layernorm(hidden_states)

        hidden_states_cls = None
        if self.num_cls_tokens > 0:
            hidden_states_cls = hidden_states_norm[:, :self.num_cls_tokens]
            hidden_states = hidden_states_norm[:, self.num_cls_tokens:]

        return hidden_states, hidden_states_norm
